#!/usr/bin/env bash
# Tiny local PostgreSQL copy of the Kinder DB, so the site runs on this Mac without
# the remote server. Everything lives in local_db/ (git-ignored):
#
#   local_db/pgdata/        the cluster (port 5433, 127.0.0.1 only, trust auth)
#   local_db/seed.sql.gz    full schema + a small data sample (what `init` loads)
#   local_db/server.log     postgres log
#
#   scripts/local_db.sh init      create the cluster + load seed.sql.gz (offline)
#   scripts/local_db.sh start     start the cluster
#   scripts/local_db.sh stop      stop the cluster
#   scripts/local_db.sh status    running? + DB size + row counts
#   scripts/local_db.sh refresh   re-pull schema + sample from the live DB (READ-ONLY:
#                                 pg_dump --schema-only and SELECT/COPY TO only),
#                                 rewrite seed.sql.gz and reload the local DB
#   scripts/local_db.sh seal      save the current local DB as seed.sql.gz
#   scripts/local_db.sh env       (re)write kinder.local.env = kinder.env with PG_* -> local
#   scripts/local_db.sh psql      psql shell on the local DB
#
# Run the app against it (kinder.env is never touched):
#   KINDER_ENV_FILE=kinder.local.env uv run python run.py     (-> http://127.0.0.1:8005)
# (KINDER_ENV_FILE is read in app/paths.py; kinder.local.env also sets DEBUG=true so no
#  background jobs -- backups, TNS download, Slack -- run against the local copy.)
#
# Objects copied by `refresh`: LOCAL_DB_OBJECTS (TNS names without prefix) overrides
# the default list below.
set -euo pipefail
# macOS: postgres refuses to start ("postmaster became multithreaded") without a valid LC_ALL.
export LC_ALL="${LC_ALL:-C}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/local_db"
PGDATA="$DIR/pgdata"
SOCK="$DIR/run"
SEED="$DIR/seed.sql.gz"
LOG="$DIR/server.log"
PORT="${LOCAL_DB_PORT:-5433}"
DB=Kinder              # app/db/__init__.py hard-codes the database name
LUSER=kinder           # local superuser (trust auth, password ignored)

BIN="${PG_BIN:-}"
if [ -z "$BIN" ]; then
  for d in /opt/homebrew/opt/postgresql@18/bin /opt/homebrew/bin /usr/local/bin; do
    [ -x "$d/initdb" ] && { BIN="$d"; break; }
  done
fi
[ -x "$BIN/initdb" ] || { echo "PostgreSQL binaries not found (set PG_BIN)" >&2; exit 1; }

OBJECTS="${LOCAL_DB_OBJECTS:-2024ggi 2025wny 2026afqd 2026adiy 2026aebg 2026adof 2026aesd 2026aedd 2026aelx 2026aett}"

lpsql() { "$BIN/psql" -X -q -v ON_ERROR_STOP=1 -h 127.0.0.1 -p "$PORT" -U "$LUSER" "$@"; }

running() { "$BIN/pg_ctl" -D "$PGDATA" status >/dev/null 2>&1; }

start() {
  [ -d "$PGDATA" ] || { echo "no cluster yet: run '$0 init'" >&2; exit 1; }
  if running; then echo "local DB already running on 127.0.0.1:$PORT"; return; fi
  mkdir -p "$SOCK"
  "$BIN/pg_ctl" -D "$PGDATA" -l "$LOG" -w \
    -o "-p $PORT -c listen_addresses=127.0.0.1 -c unix_socket_directories='$SOCK'" start >/dev/null
  echo "local DB running on 127.0.0.1:$PORT (log: $LOG)"
}

stop() {
  if running; then "$BIN/pg_ctl" -D "$PGDATA" -m fast -w stop >/dev/null; echo "local DB stopped"
  else echo "local DB not running"; fi
}

write_env() {
  # kinder.local.env: a copy of kinder.env with the DB pointed here and DEBUG on.
  local src="$ROOT/kinder.env" dst="$ROOT/kinder.local.env"
  [ -f "$src" ] || src="$ROOT/kinder.env.example"
  { echo "# Generated by scripts/local_db.sh env -- kinder.env with the local test DB."
    echo "# Use: KINDER_ENV_FILE=kinder.local.env uv run python run.py"
    grep -vE '^[[:space:]]*(PG_HOST|PG_PORT|PG_USER|PG_PASSWORD|PG_DATABASE|DEBUG|PORT|SLACK_[A-Z_]*)[[:space:]]*=' "$src" || true
    echo
    echo "# ---- local overrides ----"
    echo "PG_HOST=127.0.0.1"
    echo "PG_PORT=$PORT"
    echo "PG_DATABASE=$DB"
    echo "PG_USER=$LUSER"
    echo "PG_PASSWORD=local"
    echo "DEBUG=true"
    echo "PORT=${LOCAL_APP_PORT:-8005}"
    echo "SLACK_BOT_TOKEN="
  } > "$dst"
  chmod 600 "$dst"
  echo "wrote $dst"
}

create_cluster() {
  if [ -d "$PGDATA" ]; then echo "cluster exists: $PGDATA"; return; fi
  mkdir -p "$DIR"
  "$BIN/initdb" -D "$PGDATA" -U "$LUSER" --auth=trust -E UTF8 --locale=C >/dev/null
  echo "created cluster $PGDATA"
}

load_seed() {
  [ -f "$SEED" ] || { echo "no $SEED: run '$0 refresh' (needs the live DB once)" >&2; exit 1; }
  lpsql -d postgres -c "DROP DATABASE IF EXISTS \"$DB\" WITH (FORCE)" -c "CREATE DATABASE \"$DB\""
  gunzip -c "$SEED" | lpsql -d "$DB" >/dev/null
  echo "loaded $(basename "$SEED") into $DB"
}

status() {
  if running; then
    echo "local DB running on 127.0.0.1:$PORT  ($PGDATA)"
    lpsql -d "$DB" -At -c "SELECT 'size: '||pg_size_pretty(pg_database_size(current_database()))" \
      -c "SELECT 'objects: '||string_agg(name_prefix||' '||name, ', ' ORDER BY name) FROM transient.objects"
  else
    echo "local DB stopped ($([ -d "$PGDATA" ] && echo "cluster at $PGDATA" || echo "no cluster; run init"))"
  fi
  [ -f "$SEED" ] && echo "seed: $SEED ($(du -h "$SEED" | cut -f1))" || true
}

# ---------------------------------------------------------------- refresh (live, read-only)
refresh() {
  local envf="$ROOT/kinder.env"
  [ -f "$envf" ] || { echo "kinder.env needed for the live credentials" >&2; exit 1; }
  local RH RP RU RPW
  RH=$(grep -E '^PG_HOST=' "$envf" | tail -1 | cut -d= -f2-)
  RP=$(grep -E '^PG_PORT=' "$envf" | tail -1 | cut -d= -f2-)
  RU=$(grep -E '^PG_USER=' "$envf" | tail -1 | cut -d= -f2-)
  RPW=$(grep -E '^PG_PASSWORD=' "$envf" | tail -1 | cut -d= -f2-)
  case "$RH" in 127.0.0.1|localhost) [ "$RP" = "$PORT" ] && { echo "kinder.env points at the local DB" >&2; exit 1; };; esac
  # Every live session is forced read-only on the server side; fail fast if it is down.
  export PGCONNECT_TIMEOUT=10
  rpsql() { PGPASSWORD="$RPW" PGOPTIONS="-c default_transaction_read_only=on" \
            "$BIN/psql" -X -q -v ON_ERROR_STOP=1 -h "$RH" -p "$RP" -U "$RU" -d "$DB" "$@"; }

  # The live link (VPN) drops connections now and then: retry each read a few times.
  retry() { local i; for i in 1 2 3; do "$@" && return 0; echo "  live DB read failed (attempt $i/3)" >&2; sleep 3; done; return 1; }

  if ! rpsql -At -c "SELECT 1" >/dev/null 2>&1; then
    echo "live DB $RH:$RP unreachable (10 s timeout) -- seed left unchanged" >&2; exit 1
  fi

  create_cluster
  start
  local tmp; tmp="$(mktemp -d "$DIR/refresh.XXXX")"; trap "rm -rf '$tmp'" EXIT   # expanded now: $tmp is local and gone when the EXIT trap runs

  echo "schema from $RH:$RP (pg_dump --schema-only) ..."
  retry env PGPASSWORD="$RPW" PGOPTIONS="-c default_transaction_read_only=on" \
    "$BIN/pg_dump" -h "$RH" -p "$RP" -U "$RU" -d "$DB" --schema-only --no-owner --no-privileges \
    -f "$tmp/schema.sql"

  lpsql -d postgres -c "DROP DATABASE IF EXISTS \"$DB\" WITH (FORCE)" -c "CREATE DATABASE \"$DB\""
  lpsql -d "$DB" -f "$tmp/schema.sql" >/dev/null

  local names; names="'$(echo $OBJECTS | sed "s/ /','/g")'"
  local ids
  ids=$(retry rpsql -At -c "SELECT string_agg(obj_id::text, ',') FROM transient.objects WHERE name IN ($names)")
  [ -n "$ids" ] || { echo "none of the objects found: $OBJECTS" >&2; exit 1; }
  local OBJ="obj_id IN ($ids)"

  # table|WHERE clause (parents before children for the FKs)
  local spec=(
    "auth.users|true"
    "auth.groups|true"
    "auth.usr_group|true"
    "auth.system_settings|true"
    "obs.targets|true"
    "obs.direct_trigger_targets|true"
    "obs.logs|log_id IN (SELECT log_id FROM obs.logs ORDER BY date DESC NULLS LAST LIMIT 100)"
    "transient.default_permissions|true"
    "transient.objects|$OBJ"
    "transient.photometry|$OBJ"
    "transient.spectroscopy|$OBJ"
    "transient.comments|$OBJ"
    "transient.cross_matches|$OBJ"
    "transient.detect_screen|$OBJ"
    "transient.detect_screen_history|$OBJ"
    "transient.target_images|$OBJ"
    "transient.custom_targets|$OBJ"
    "transient.object_views|$OBJ"
    "transient.object_views_detail|$OBJ"
    "transient.tns_update_audit|$OBJ"
    "transient.object_source_permissions|object_name IN ($names)"
    "transient.download_logs|log_id IN (SELECT log_id FROM transient.download_logs ORDER BY download_date DESC NULLS LAST LIMIT 20)"
  )
  local s t w n
  for s in "${spec[@]}"; do
    t="${s%%|*}"; w="${s#*|}"
    retry rpsql -c "\\copy (SELECT * FROM $t WHERE $w) TO '$tmp/data.copy'"
    lpsql -d "$DB" -c "COPY $t FROM STDIN" < "$tmp/data.copy"
    n=$(lpsql -d "$DB" -At -c "SELECT count(*) FROM $t")
    printf '  %-40s %6s rows\n' "$t" "$n"
  done
  seal
}

# Strip API keys, move sequences past the copied ids, dump the local DB to seed.sql.gz.
seal() {

  # No live API keys in the local copy; sequences continue after the copied ids.
  lpsql -d "$DB" >/dev/null <<'SQL'
UPDATE auth.users SET api_key = NULL, api_key_hash = NULL, api_key_hint = NULL;
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT s.oid::regclass AS seq, t.oid::regclass AS tbl, a.attname AS col
    FROM pg_class s
    JOIN pg_depend d ON d.objid = s.oid AND d.deptype IN ('a','i')
    JOIN pg_class t ON t.oid = d.refobjid
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
    WHERE s.relkind = 'S'
  LOOP
    EXECUTE format('SELECT setval(%L, COALESCE((SELECT max(%I) FROM %s), 0) + 1, false)', r.seq, r.col, r.tbl);
  END LOOP;
END $$;
VACUUM ANALYZE;
SQL

  "$BIN/pg_dump" -h 127.0.0.1 -p "$PORT" -U "$LUSER" -d "$DB" --no-owner --no-privileges \
    | gzip -9 > "$SEED.tmp"
  mv "$SEED.tmp" "$SEED"
  echo "seed written: $SEED ($(du -h "$SEED" | cut -f1))"
}

case "${1:-}" in
  init)    create_cluster; start; load_seed; write_env; status ;;
  start)   start ;;
  stop)    stop ;;
  status)  status ;;
  refresh) refresh; write_env; status ;;
  seal)    seal ;;
  env)     write_env ;;
  psql)    shift; exec "$BIN/psql" -h 127.0.0.1 -p "$PORT" -U "$LUSER" -d "$DB" "$@" ;;
  *) sed -n '2,25p' "$0"; exit 2 ;;
esac
